def trace_mask(outline):
    points = [tuple(2 * int(value) for value in pair.split(",")) for pair in outline.split()]
    mask = Image.new("L", SIZE, 0)
    ImageDraw.Draw(mask).polygon(points, fill=255)
    return mask


def save_layer(layer, name):
    layer = layer.resize((1392, round(layer.height * 0.725)), Image.Resampling.LANCZOS)
    canvas = Image.new("RGBA", SIZE)
    canvas.alpha_composite(layer, dest=(-226, 157))
    canvas.save(PROJECT / "public/art" / f"brand-{name}.webp", lossless=True, method=5)


def paint_water(blue, wet):
    # 映射录屏中海面的明暗，包括码头在背光面投下的倒影。
    tone = np.clip((blue - 25) / 38, 0, 1)
    tone = np.where(wet > 0.55, tone, 0.53)
    tone = np.pad(tone, ((0, 130), (0, 0)), mode="reflect")
    low = np.array([50, 119, 123])
    high = np.array([148, 189, 175])
    color = (low + (high - low) * tone[:, :, None]).astype("uint8")
    water = Image.fromarray(color).convert("RGBA")
    contour = [(160, 391), (181, 364), (272, 329), (354, 312), (459, 351),
               (595, 361), (689, 382), (739, 346), (824, 387), (860, 431),
               (824, 460), (802, 483), (814, 506), (789, 516), (729, 516),
               (689, 533), (633, 534), (560, 561), (507, 568), (444, 556),
               (414, 547), (370, 551), (348, 541), (316, 527), (279, 524),
               (259, 511), (229, 502), (232, 486), (190, 473), (169, 456),
               (187, 448), (144, 428), (170, 415)]
    mask = Image.new("L", water.size)
    ImageDraw.Draw(mask).polygon([(2*x, 2*y) for x, y in contour], fill=211)
    # 双重羽化保留港内水色，沿外围约四十像素逐渐露出纸色。
    soft = Image.blend(mask.filter(ImageFilter.GaussianBlur(22)),
                       mask.filter(ImageFilter.GaussianBlur(44)), 0.42)
    water.putalpha(soft)
    return water


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, nargs="?", default=Path("J:/素材/pv1.mp4"))
    source = parser.parse_args().source
    command = [find_ffmpeg(), "-loglevel", "error", "-ss", "9.00", "-i", source, "-frames:v",
               "1", "-f", "image2pipe", "-c:v", "png", "pipe:1"]
    frame = Image.open(io.BytesIO(subprocess.check_output(command))).convert("RGB")
    if frame.size != SIZE:
        raise ValueError("请使用 1920×1080 的原始 pv1.mp4")
    # 轻提中间调，保留城墙和瓦片的立体阴影。
    lifted = frame.point([round(255 * (v / 255) ** 0.86) for v in range(256)] * 3)
    lifted = ImageEnhance.Color(lifted).enhance(1.09)
    rgb = np.asarray(frame, dtype=float)
    red, green, blue = rgb.transpose(2, 0, 1)
    # 从描边区域中扣去实录的深蓝海水，保留桩下的空隙。
    water = np.minimum(blue - green - 4, green - red - 4)
    dry = 1 - np.clip(water / 11, 0, 1)
    save_layer(paint_water(blue, 1 - dry), "water")
    for name, outline in [("harbor", HARBOR), ("wharf", WHARF)]:
        mask = np.asarray(trace_mask(outline), dtype=float)
        mask[650:] *= dry[650:]
        layer = lifted.copy().convert("RGBA")
        layer.putalpha(Image.fromarray(mask.astype("uint8")).filter(ImageFilter.GaussianBlur(0.65)))
        # 两层锚在同一画布中，前后轻微错位时岸线仍与木栈道相接。
        save_layer(layer, name)


if __name__ == "__main__":
    main()
